function escapeTsString(value) {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function formatEntry(key, value) {
  const escaped = escapeTsString(value);
  if (escaped.length > 72 || escaped.includes('\n')) {
    return `  '${key}':\n    '${escaped}',`;
  }
  return `  '${key}': '${escaped}',`;
}

function buildLocaleFile(exportName, map) {
  const missing = keys.filter((k) => !map[k]);
  if (missing.length) {
    throw new Error(`Missing translations for ${exportName}: ${missing.join(', ')}`);
  }

  const lines = keys.map((k) => formatEntry(k, map[k]));
  return `import type { AppTranslationKey } from '../keys';\n\nexport const ${exportName}: Record<AppTranslationKey, string> = {\n${lines.join('\n')}\n};\n`;
}

